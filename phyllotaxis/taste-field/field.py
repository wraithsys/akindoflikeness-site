def pcs(ch): return sorted(set(m%12 for m in ch))
def rough(ch):
    p=pcs(ch); r=0
    for a,b in itertools.combinations(p,2):
        d=min((b-a)%12,(a-b)%12)
        if d==1: r+=2
        if d==6: r+=1
        if d==2: r+=0.5
    return r
def feats(seq,n_exp):
    L=len(seq); first,last=seq[0],seq[-1]; f={}
    f["wobble3"]=1.0 if (L==3 and pcs(first)==pcs(last) and first[0]%12==last[0]%12) else 0.0
    f["return_end"]=1.0 if (L>3 and pcs(first)==pcs(last)) else 0.0
    f["lands_home"]=1.0 if last[0]%12==first[0]%12 else 0.0
    f["colour"]=sum(len({(m-c[0])%12 for m in c}&{1,2,5,9,10,11}) for c in seq)/L
    def pm(ch):
        p=set(pcs(ch)); return any({r,(r+4)%12,(r+7)%12}==p for r in p)
    f["plain_major_frac"]=sum(pm(c) for c in seq)/L
    sb=wb=ct=jmp=0
    for a,b in zip(seq,seq[1:]):
        d=min((b[0]-a[0])%12,(a[0]-b[0])%12)
        sb+=d==1; wb+=d==2; ct+=len(set(pcs(a))&set(pcs(b)))
        jmp+=abs(sum(b)/len(b)-sum(a)/len(a))>7
    T=L-1
    f["semitone_bass"]=sb/T; f["wholetone_bass"]=wb/T; f["common_tones"]=ct/T; f["jump_frac"]=jmp/T
    f["teleport"]=1.0 if any(pcs(a)==pcs(b) and abs(sum(b)/len(b)-sum(a)/len(a))>=10 for a,b in zip(seq,seq[1:])) else 0.0
    rs=[rough(c) for c in seq]; mx=max(rs)
    f["late_spike"]=1.0 if (mx>0 and rs.index(mx)==L-2 and rs[-1]<mx) else 0.0
    rl={(m-last[0])%12 for m in last}
    f["arrival_palette"]=1.0 if (rl&{1,3,8,10}) and 4 not in rl else 0.0
    f["soprano_return"]=1.0 if max(last)%12==max(first)%12 else 0.0
    f["length"]=L; f["exposure"]=min(n_exp,8); f["wear"]=max(0,n_exp-4)
    return f

